export function getLevelConfig(levelNum = 1) {
  const lvl = Math.max(1, Math.min(TRAIN_LEVELS.length, parseInt(levelNum, 10) || 1));
  return TRAIN_LEVELS.find((l) => l.level === lvl) || TRAIN_LEVELS[0];
}

export function getGradeForLevel(levelNum = 1) {
  return levelNum <= 9 ? 'Pre-K' : 'Kindergarten';
}
